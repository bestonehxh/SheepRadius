    /// The comparable part of a fingerprint for a **tunnelled** session.
    ///
    /// A rejection decided inside the tunnel rejects the outer session — that is the point,
    /// and it is proved — but FreeRADIUS answers the outer request with a bare EAP-Failure,
    /// so none of the reply attributes come back out. Measured, including with an explicit
    /// `update outer.reply`, which does not change it. Comparing those attributes would
    /// therefore be comparing FreeRADIUS's tunnel behaviour and not the policy, so a reject
    /// is compared on the verdict and the rules that fired.
    static func tunnelled(_ fingerprint: String) -> String {
        guard fingerprint.hasPrefix("verdict=reject") else { return fingerprint }
        return fingerprint.split(separator: " ")
            .filter { $0.hasPrefix("verdict=") || $0.hasPrefix("rules=") }
            .joined(separator: " ")
    }

    /// One comparable string: the verdict, the VLAN, and every attribute a probe rule can set.
    /// Deliberately not "every attribute in the reply" — Message-Authenticator and friends are
    /// noise, and the point is what the *policy* decided.
    static let watched = ["Tunnel-Private-Group-Id", "Session-Timeout", "Filter-Id", "Class",
                          "Reply-Message"]

    /// `Class` is an `octets` attribute, so radclient prints it as `0x70726f…` — the same
    /// bytes, in the spelling its type calls for. Decoded here so the two sides of the
    /// comparison are comparing the value and not the notation.
    static func normalized(_ value: String) -> String {
        guard value.hasPrefix("0x"), value.count % 2 == 0 else { return value }
        let hex = value.dropFirst(2)
        guard !hex.isEmpty, hex.allSatisfy(\.isHexDigit) else { return value }
        var bytes: [UInt8] = []
        var index = hex.startIndex
        while index < hex.endIndex {
            let next = hex.index(index, offsetBy: 2)
            guard let byte = UInt8(hex[index..<next], radix: 16) else { return value }
            bytes.append(byte)
            index = next
        }
        guard let text = String(bytes: bytes, encoding: .utf8),
              !text.isEmpty, text.unicodeScalars.allSatisfy({ $0.value >= 32 && $0.value < 127 }) else {
            return value
        }
        return text
    }

    static func fingerprint(rejected: Bool, values: [String: String], rules: [String]) -> String {
        var parts = ["verdict=" + (rejected ? "reject" : "accept")]
        for name in watched {
            parts.append("\(name)=\(values[name].map(normalized) ?? "-")")
        }
        parts.append("rules=" + (rules.isEmpty ? "-" : rules.joined(separator: ",")))
        return parts.joined(separator: " ")
    }

    /// The evaluator's side of the comparison.
    static func predicted(user: LabUser, groupNames: [String], doc: LabDocument,
                          request: PolicyRequest) -> String {
        let result = PolicyEvaluator.evaluate(user: user, groups: groupNames.map { LabGroup(name: $0) },
                                              rules: doc.rules, context: PolicyContext(doc),
                                              request: request)
        var values: [String: String] = [:]
        for line in result.lines where watched.contains(line.name) {
            values[line.name] = line.value.trimmingCharacters(in: CharacterSet(charactersIn: "\""))
        }
        return fingerprint(rejected: result.rejected, values: values, rules: result.firedRules)
    }
}

// MARK: - One line for the Users and Groups panes

/// "rule 3 · Group NetAdmins → VLAN 10" — the whole of what Users and Groups say about RADIUS
/// (build 13). They used to carry an editable VLAN, a reply-attribute box and a resolved-reply
/// panel; now they carry this sentence and a link, because there is exactly one place a reply
/// is decided and this is not it.
///
/// Only the **user-side** half of a condition can be answered without a request, so a rule that
/// also tests an SSID or a NAS is reported as a candidate that "depends on the request" rather
/// than guessed at — the same honesty the Preview has always had about raw conditions.
nonisolated enum PolicySummary {
    nonisolated struct Line: Sendable, Equatable {
        /// "rule 3 · Group NetAdmins → VLAN 10", or the no-match sentence.
        var text: String
        var ruleID: UUID?
        /// False when the first candidate rule still needs something out of the request.
        var certain = true
    }

    static let noMatch = "no rule — VLAN of the port/SSID"

    static func forUser(_ user: LabUser, groupNames: [String], doc: LabDocument) -> Line {
        let context = PolicyContext(doc)
        let mine = groupNames.map { LabGroup(name: $0) }
        for (index, rule) in doc.rules.enumerated() where rule.enabled {
            let userSide = rule.conditions.filter { $0.kind.isUserSide }
            let requestSide = rule.conditions.count - userSide.count
            let truths = userSide.map {
                PolicyEvaluator.holds($0, user: user, groups: mine, context: context,
                                      request: PolicyRequest())
            }
            let name = "rule \(index + 1) · \(rule.displayName(index: index, context: context))"
            if rule.match == .all {
                if truths.contains(.no) { continue }
                let certain = requestSide == 0 && !truths.contains(.unknown)
                return Line(text: name, ruleID: rule.id, certain: certain)
            }
            // any-of: one true user-side condition is already enough.
            if truths.contains(.yes) { return Line(text: name, ruleID: rule.id, certain: true) }
            if requestSide > 0 || truths.contains(.unknown) {
                return Line(text: name, ruleID: rule.id, certain: false)
            }
        }
        return Line(text: noMatch, ruleID: nil)
    }

    /// **The user as the directory has them** — which since build 21 is the only way there is.
    ///
    /// A rule names its group, the directory names its groups, and the generated unlang
    /// compares `&control:Sheep-Group` by name: one vocabulary, end to end, with nothing to
    /// translate. A rule naming a group this user is not in simply does not match, which is
    /// the truthful answer.
    static func forDirectoryUser(_ user: DirectoryUser, doc: LabDocument) -> Line {
        forUser(LabUser(username: user.username, ou: user.ou), groupNames: user.groups, doc: doc)
    }

    /// And for a directory group: what a member of it and nothing else would get.
    static func forDirectoryGroup(_ group: DirectoryGroup, doc: LabDocument) -> Line {
        forUser(LabUser(username: ""), groupNames: [group.name], doc: doc)
    }
}

/// Predicts exactly what `RuleUnlang` will make radiusd do.
///
/// This is the pane's preview *and* the thing the live suite proves against the real server:
/// `./Tests/run.sh live` drives a matrix of requests through radclient and compares the reply
/// and the fired rules with this. If the two ever disagree, that test fails — which is the
/// only reason it is safe to have the logic written twice.
nonisolated enum PolicyEvaluator {

    static func evaluate(user: LabUser, groups: [LabGroup], rules: [PolicyRule],
                         context: PolicyContext, request: PolicyRequest) -> PolicyResult {
        // Build 13: there is no static reply to start from. The list *is* the policy, and a
        // request that matches nothing leaves with an Access-Accept and no VLAN.
        var result = PolicyResult()

        var stopped = false
        for (index, rule) in rules.enumerated() {
            let name = rule.displayName(index: index, context: context)
            guard rule.enabled else {
                result.traces.append(.init(id: rule.id, index: index, name: name, verdict: .disabled))
                continue
            }
            guard !stopped else {
                result.traces.append(.init(id: rule.id, index: index, name: name, verdict: .notReached))
                continue
            }
            let truth = matches(rule, user: user, groups: groups, context: context, request: request)
            switch truth {
            case .unknown:
                result.approximate = true
                result.traces.append(.init(id: rule.id, index: index, name: name, verdict: .unknown,
                                            note: "only radiusd can decide a raw condition"))
                // A rule that might match and might stop makes everything after it uncertain.
                if rule.stopAfterMatch { stopped = true }
            case .no:
                result.traces.append(.init(id: rule.id, index: index, name: name, verdict: .skipped))
            case .yes:
                result.traces.append(.init(id: rule.id, index: index, name: name, verdict: .matched))
                apply(rule, named: name, to: &result)
                if rule.stopAfterMatch { stopped = true }
            }
        }
        return result
    }

    /// `update reply { }` semantics: `:=` replaces every value of that attribute, `=` only
    /// sets it when it is not there, `+=` appends.
    private static func set(_ name: String, _ op: String, _ value: String, source: String,
                            in lines: inout [PolicyLine]) {
        switch op {
        case ":=":
            lines.removeAll { $0.name == name }
            lines.append(.init(name: name, op: op, value: value, source: source))
        case "=":
            guard !lines.contains(where: { $0.name == name }) else { return }
            lines.append(.init(name: name, op: op, value: value, source: source))
        default:
            lines.append(.init(name: name, op: op, value: value, source: source))
        }
    }

    private static func apply(_ rule: PolicyRule, named name: String, to result: inout PolicyResult) {
        let source = "rule: \(name)"
        let vlan = rule.vlan.trimmingCharacters(in: .whitespaces)
        if !vlan.isEmpty {
            set("Tunnel-Type", ":=", "VLAN", source: source, in: &result.lines)
            set("Tunnel-Medium-Type", ":=", "IEEE-802", source: source, in: &result.lines)
            set("Tunnel-Private-Group-Id", ":=", "\"\(ConfigGenerator.quoted(vlan))\"",
                source: source, in: &result.lines)
        }
        for attribute in rule.sentAttributes {
            set(attribute.name, attribute.op, attribute.value, source: source, in: &result.lines)
        }
        let timeout = rule.sessionTimeout.trimmingCharacters(in: .whitespaces)
        if rule.sendsAttributes, !timeout.isEmpty, Int(timeout) != nil {
            set("Session-Timeout", ":=", timeout, source: source, in: &result.lines)
        }
        let message = rule.rejectMessage.trimmingCharacters(in: .whitespaces)
        if rule.rejects {
            if !message.isEmpty {
                set("Reply-Message", ":=", "\"\(ConfigGenerator.quoted(message))\"", source: source, in: &result.lines)
                result.rejectMessage = message
            }
            result.rejected = true
        }
    }

    // MARK: Conditions

    static func matches(_ rule: PolicyRule, user: LabUser, groups: [LabGroup],
                        context: PolicyContext, request: PolicyRequest) -> Truth {
        let truths = rule.conditions.map { holds($0, user: user, groups: groups, context: context, request: request) }
        guard !truths.isEmpty else { return .yes }
        return rule.match == .all
            ? truths.reduce(Truth.yes) { $0 && $1 }
            : truths.reduce(Truth.no) { $0 || $1 }
    }

    static func holds(_ c: RuleCondition, user: LabUser, groups: [LabGroup],
                      context: PolicyContext, request: PolicyRequest) -> Truth {
        let value = c.value.trimmingCharacters(in: .whitespaces)
        switch c.kind {
        case .groupIs, .groupIsNot:
            let name = value
            guard !name.isEmpty else { return .no }
            // `==` on a string is case-sensitive in unlang, so it is here too.
            let member = groups.contains { $0.name == name }
            return c.kind == .groupIs ? truth(member) : truth(!member)
        case .ouIs:
            let path = OUPath.normalized(value)
            guard !path.isEmpty else { return .no }
            return truth(user.effectiveOU == path)
        case .ouIsUnder:
            let path = OUPath.normalized(value)
            guard !path.isEmpty else { return .no }
            let mine = user.effectiveOU
            return truth(mine == path || mine.hasPrefix(path + "/"))
        case .usernameIs:
            guard !value.isEmpty else { return .no }
            return truth(user.username == value)
        case .usernameEndsWith:
            guard !value.isEmpty else { return .no }
            return truth(user.username.hasSuffix(value))
        case .usernameMatches:
            guard !value.isEmpty else { return .no }
            return truth(matchesRegex(user.username, value, caseInsensitive: false))
        case .nasIPIs:
            guard Validation.isValidAddress(value), !value.contains("/") else { return .no }
            return truth(ipv4(request.nasIPAddress) != nil && ipv4(request.nasIPAddress) == ipv4(value))
        case .nasIPInCIDR:
            guard Validation.isValidAddress(value) else { return .no }
            return truth(inside(request.nasIPAddress, value))
        case .nasClient:
            guard let address = context.clientAddress(c.reference), Validation.isValidAddress(address) else { return .no }
            return truth(inside(request.nasIPAddress, address))
        case .nasIdentifierIs:
            guard !value.isEmpty else { return .no }
            return truth(request.nasIdentifier == value)
        case .nasIdentifierMatches:
            guard !value.isEmpty else { return .no }
            return truth(!request.nasIdentifier.isEmpty
                         && matchesRegex(request.nasIdentifier, value, caseInsensitive: false))
        case .portType:
            guard let type = RulePortType(rawValue: value) else { return .no }
            return truth(request.nasPortType == type.rawValue)
        case .ssid:
            guard !value.isEmpty else { return .no }
            return truth(request.calledStationID.hasSuffix(":" + value))
        case .calledStationIs:
            guard !value.isEmpty else { return .no }
            return truth(request.calledStationID == value)
        case .calledStationBeginsWith:
            guard !value.isEmpty else { return .no }
            return truth(!request.calledStationID.isEmpty && request.calledStationID.hasPrefix(value))
        case .callingMACIs:
            guard let digits = RuleUnlang.macDigits(value),
                  let sent = RuleUnlang.macDigits(request.callingStationID) else { return .no }
            return truth(digits == sent)
        case .callingMACMatches:
            guard !value.isEmpty else { return .no }
            return truth(!request.callingStationID.isEmpty
                         && matchesRegex(request.callingStationID, value, caseInsensitive: true))
        case .timeWindow:
            return truth(inWindow(c, at: request.date))
        case .anyone:
            return .yes
        case .isComputerAccount:
            // The evaluator is only ever asked about a person — Users ▸ Properties and the
            // Preview strip both start from a `LabUser`, and a machine account is never one.
            // The tag is still tested rather than answered `.no` outright, so a lab that
            // really does have a group of that name previews the way radiusd will behave.
            return truth(groups.contains { $0.name == MachineIdentity.groupTag })
        case .raw:
            return value.isEmpty ? .no : .unknown
        }
    }

    private static func truth(_ b: Bool) -> Truth { b ? .yes : .no }

    /// Local calendar, matching `%H%G` and rlm_date's `%a`, both of which radiusd renders in
    /// this Mac's own time zone.
    static func inWindow(_ c: RuleCondition, at date: Date) -> Bool {
        let days = c.normalizedWeekdays
        guard !days.isEmpty else { return false }
        var calendar = Calendar(identifier: .gregorian)
        calendar.locale = Locale(identifier: "en_US_POSIX")
        let parts = calendar.dateComponents([.hour, .minute, .weekday], from: date)
        guard let hour = parts.hour, let minute = parts.minute, let weekday = parts.weekday else { return false }
        // Calendar's weekday is 1 = Sunday; the model is 1 = Monday.
        let mondayFirst = weekday == 1 ? 7 : weekday - 1
        if days.count < 7, !days.contains(mondayFirst) { return false }
        guard !c.isAllDay else { return true }
        let now = hour * 100 + minute
        let from = clock(c.fromMinute), to = clock(c.toMinute)
        return c.fromMinute <= c.toMinute ? (now >= from && now <= to) : (now >= from || now <= to)
    }

    private static func clock(_ minutes: Int) -> Int {
        let clamped = max(0, min(1439, minutes))
        return (clamped / 60) * 100 + clamped % 60
    }

    /// The same partial match `=~` performs — unanchored unless the pattern says otherwise.
    static func matchesRegex(_ subject: String, _ pattern: String, caseInsensitive: Bool) -> Bool {
        guard let regex = try? NSRegularExpression(
            pattern: pattern, options: caseInsensitive ? [.caseInsensitive] : []) else { return false }
        let range = NSRange(subject.startIndex..., in: subject)
        return regex.firstMatch(in: subject, options: [], range: range) != nil
    }

    /// Dotted quad → host order, or nil.
    static func ipv4(_ s: String) -> UInt32? {
        let parts = s.split(separator: ".", omittingEmptySubsequences: false)
        guard parts.count == 4 else { return nil }
        var out: UInt32 = 0
        for part in parts {
            guard let octet = UInt8(part) else { return nil }
            out = (out << 8) | UInt32(octet)
        }
        return out
    }

    /// True when `address` falls inside `pattern`, which may be a single IP or a CIDR.
    static func inside(_ address: String, _ pattern: String) -> Bool {
        guard let value = ipv4(address) else { return false }
        let pieces = pattern.split(separator: "/", omittingEmptySubsequences: false)
        guard let network = ipv4(String(pieces[0])) else { return false }
        guard pieces.count == 2 else { return value == network }
        guard let bits = Int(pieces[1]), (0...32).contains(bits) else { return false }
        if bits == 0 { return true }
        let mask: UInt32 = bits == 32 ? .max : ~(UInt32.max >> UInt32(bits))
        return (value & mask) == (network & mask)
    }

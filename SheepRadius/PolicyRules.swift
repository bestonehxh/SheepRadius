import Foundation

// MARK: - The site-local dictionary

/// The attributes the app declares in `raddb/dictionary` so the generated unlang can see *who*
/// the authenticating user is. They exist only inside radiusd.
///
/// **3000–3999 is the range FreeRADIUS reserves for exactly this.** Its own
/// `dictionary.freeradius.internal` says `Range: 3000-3999 · Site-local attributes (see
/// raddb/dictionary) · Do NOT define attributes in this range!` and `Range: 65536- · Invalid.`
/// Measured on 3.2.10: `radiusd -CX` accepts 65536 without a murmur, so the range has to be
/// enforced here rather than left to the parser.
///
/// An attribute number above 255 **cannot be encoded into a RADIUS packet at all**, which is
/// what makes these structurally incapable of leaking onto the wire — not a filter that could
/// be forgotten. `raddb/dictionary` is read automatically; no `$INCLUDE` is needed.
nonisolated enum SheepAttribute {
    /// Every group the user belongs to, one value each, in membership order.
    static let group = "Sheep-Group"
    /// The user's OU path, `/`-separated (`Staff/IT`).
    static let ou = "Sheep-OU"
    /// One value per rule that matched — the app reads these back out of the debug stream.
    static let rule = "Sheep-Rule"
    /// Set on `&outer.session-state:` by the inner tunnel, so the outer post-auth knows the
    /// rules have already run with the real identity. See `RuleUnlang.postAuth`.
    static let handled = "Sheep-Handled"

    static let numbers: [(name: String, number: Int)] = [
        (group, 3000), (ou, 3001), (rule, 3002), (handled, 3003),
    ]

    /// Site-local range, as FreeRADIUS defines it.
    static let validRange = 3000...3999

    static var dictionary: String {
        var out = """
        # Generated by SheepRadius — edits are overwritten on Apply.
        #
        # Site-local attributes, in the 3000-3999 range FreeRADIUS reserves for this file.
        # They are how the Policy pane's rules know who is authenticating. Numbers above 255
        # cannot be encoded into a RADIUS packet, so none of these can reach the wire.

        """
        for item in numbers {
            out += "ATTRIBUTE\t\(item.name)\t\(item.number)\tstring\n"
        }
        return out
    }
}

// MARK: - The rule model

nonisolated enum RuleMatch: String, Codable, CaseIterable, Sendable {
    case all, any

    var label: String { self == .all ? "all of" : "any of" }
    /// How the generated conditions are joined. Each one is parenthesised already.
    var joiner: String { self == .all ? " && " : " || " }
}

nonisolated enum ConditionKind: String, Codable, CaseIterable, Sendable {
    case groupIs, groupIsNot
    case ouIs, ouIsUnder
    case usernameIs, usernameEndsWith, usernameMatches
    case nasIPIs, nasIPInCIDR, nasClient
    case nasIdentifierIs, nasIdentifierMatches
    case portType
    case ssid
    case calledStationIs, calledStationBeginsWith
    case callingMACIs, callingMACMatches
    case timeWindow
    case anyone
    /// **Build 24.** The identity is a domain-joined computer rather than a person — see
    /// `MachineIdentity`. It is a `groupIs` against a fixed name and is written as one; it
    /// exists as its own kind so the dropdown can say what it means without anybody having to
    /// know that the tag happens to be spelled "Domain Computers".
    case isComputerAccount
    case raw

    /// **All twenty-one, in four groups** (build 25, QA M-23).
    ///
    /// Build 13's flat list of fourteen was chosen to keep the dropdown short, and eight kinds
    /// were simply unreachable from it: `groupIsNot`, `ouIs`, `ouIsUnder`, `nasIPIs`,
    /// `nasIdentifierMatches`, `ssid`, `callingMACMatches` and `raw`. Every one of them
    /// decodes, generates and evaluates — they are tested in `unit.swift` and always have
    /// been — so the only thing missing was a way in. "User is not in group" and "User's OU
    /// is" are ordinary requests, and `raw` is the escape hatch a lab needs when nothing else
    /// fits.
    ///
    /// Twenty-one flat items is a menu nobody can read, so they are grouped by **what the
    /// condition is about**: the identity, where the request came from, what it came over,
    /// and everything else. The order inside each group is build 13's, so a person who knew
    /// where "User is" was still finds it in the same place.
    nonisolated struct Group: Sendable, Equatable, Identifiable {
        var title: String
        var kinds: [ConditionKind]
        var id: String { title }
    }

    static let groupedMenu: [Group] = [
        Group(title: "The account", kinds: [
            .groupIs, .groupIsNot, .ouIs, .ouIsUnder,
            .usernameIs, .usernameEndsWith, .usernameMatches, .isComputerAccount,
        ]),
        Group(title: "Where the request came from", kinds: [
            .nasClient, .nasIPIs, .nasIPInCIDR, .nasIdentifierIs, .nasIdentifierMatches,
        ]),
        Group(title: "What it came over", kinds: [
            .portType, .calledStationIs, .calledStationBeginsWith, .ssid,
            .callingMACIs, .callingMACMatches,
        ]),
        Group(title: "Anything else", kinds: [.timeWindow, .anyone, .raw]),
    ]

    /// Every kind the menu offers, flat — the list `menu(including:)` used to be, and the one
    /// the unit tests count against `allCases`.
    static let menu: [ConditionKind] = groupedMenu.flatMap(\.kinds)

    /// The menu plus `current`, when that is one of the kinds the menu leaves out. Nothing is
    /// left out any more, so this can only ever return `menu` — it stays because a kind added
    /// in a later build and forgotten here would otherwise make a rule unreadable.
    static func menu(including current: ConditionKind) -> [ConditionKind] {
        menu.contains(current) ? menu : menu + [current]
    }

    /// The grouped menu with `current` put back if it is somehow not in it.
    static func groupedMenu(including current: ConditionKind) -> [Group] {
        guard !menu.contains(current) else { return groupedMenu }
        return groupedMenu + [Group(title: "In this rule", kinds: [current])]
    }

    var label: String {
        switch self {
        case .groupIs: "User is in group"
        case .groupIsNot: "User is not in group"
        case .ouIs: "User's OU is"
        case .ouIsUnder: "User's OU is under"
        case .usernameIs: "User is"
        case .usernameEndsWith: "Username ends with"
        case .usernameMatches: "Username matches (regex)"
        case .nasIPIs: "NAS-IP is"
        case .nasIPInCIDR: "NAS-IP is / in subnet"
        case .nasClient: "From NAS client"
        case .nasIdentifierIs: "NAS-Identifier is"
        case .nasIdentifierMatches: "NAS-Identifier matches (regex)"
        case .portType: "Wired or Wi-Fi"
        case .ssid: "SSID (after the last colon) is"
        case .calledStationIs: "SSID / Called-Station-Id is"
        case .calledStationBeginsWith: "SSID / Called-Station-Id begins with"
        case .callingMACIs: "Device MAC is"
        case .callingMACMatches: "Device MAC matches (regex)"
        case .timeWindow: "Time window"
        case .anyone: "Anyone"
        case .isComputerAccount: "Identity is a computer account"
        case .raw: "Raw unlang condition"
        }
    }

    /// True when the condition depends only on the user table, so Users ▸ Properties can say
    /// whether a rule applies without inventing a request. Everything else "depends on the
    /// request". `anyone` is user-side because it is true for everybody.
    var isUserSide: Bool {
        switch self {
        case .groupIs, .groupIsNot, .ouIs, .ouIsUnder,
             .usernameIs, .usernameEndsWith, .usernameMatches, .anyone, .isComputerAccount: true
        default: false
        }
    }

    /// The condition takes no value at all.
    var isValueless: Bool { self == .anyone || self == .isComputerAccount }

    /// The value field is a free-text box unless this says otherwise.
    var picksGroup: Bool { self == .groupIs || self == .groupIsNot }
    var picksOU: Bool { self == .ouIs || self == .ouIsUnder }
    var picksClient: Bool { self == .nasClient }
    var picksPortType: Bool { self == .portType }
    var isTimeWindow: Bool { self == .timeWindow }
    var isRaw: Bool { self == .raw }

    var placeholder: String {
        switch self {
        case .usernameIs: "alice"
        case .usernameEndsWith: "@lab.local"
        case .usernameMatches, .nasIdentifierMatches: "^sw-"
        case .nasIPIs: "10.0.0.1"
        case .nasIPInCIDR: "10.0.0.0/24 or 10.0.0.1"
        case .nasIdentifierIs: "sw-lab-1"
        case .ssid: "Lab-Guest"
        case .calledStationIs: "SIAM-BUILDING:test2"
        case .calledStationBeginsWith: "SIAM-BUILDING:"
        case .callingMACIs: "aa:bb:cc:dd:ee:ff"
        case .callingMACMatches: "^aa:bb:cc"
        case .raw: "&Service-Type == Framed-User"
        default: ""
        }
    }

    var hint: String {
        switch self {
        case .groupIs, .groupIsNot:
            "Matched against &control:Sheep-Group, which raddb/authorize sets from this user's group list."
        case .ouIs:

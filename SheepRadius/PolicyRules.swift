            "A regular expression, matched against User-Name. For PEAP this is the identity inside the tunnel."
        case .nasIPIs, .nasIPInCIDR, .nasClient:
            "Matched against the NAS-IP-Address the device puts in the request — not the packet's source address. A single address or a CIDR both work."
        case .nasIdentifierIs, .nasIdentifierMatches:
            "NAS-Identifier is the name the switch or AP calls itself."
        case .portType:
            "NAS-Port-Type: Ethernet for a wired switch port, Wireless-802.11 for Wi-Fi."
        case .ssid:
            "Compares the part after the last colon of Called-Station-Id. That is the SSID only if the AP puts it there — \"<AP MAC>:<SSID>\" and \"<AP group>:<SSID>\" both work, but many vendors send something else entirely. Check the Log or the Test pane for what the access points actually send, and use \"Called-Station-Id is\" when you know the whole value."
        case .calledStationIs:
            "The whole Called-Station-Id, exactly as the AP sends it, compared case-sensitively — for example SIAM-BUILDING:test2."
        case .calledStationBeginsWith:
            "A prefix of Called-Station-Id, case-sensitive. \"SIAM-BUILDING:\" — with the colon — is every SSID on that AP group."
        case .callingMACIs:
            "The client's MAC. aa:bb:…, AA-BB-…, aabb.ccdd.eeff and aabbccddeeff all match, case-insensitively."
